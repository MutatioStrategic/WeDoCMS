                </form>
                <form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>" style="display:inline-block">
                    <input type="hidden" name="action" value="veld_archive_hosted" /><input type="hidden" name="asset_id" value="<?php echo esc_attr($asset_id); ?>" /><input type="hidden" name="licence_id" value="<?php echo esc_attr($licence_id); ?>" /><input type="hidden" name="variant" value="card" /><?php wp_nonce_field('veld_archive_hosted_' . $asset_id); ?><button class="button" type="submit"><?php echo esc_html__('Get hosted shortcode', 'veld-archive'); ?></button>
