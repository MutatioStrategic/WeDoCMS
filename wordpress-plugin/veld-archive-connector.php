    private function render_asset_card($asset) {
        $asset_id = isset($asset['id']) ? sanitize_text_field($asset['id']) : '';
        $licence = isset($asset['activeLicence']) && is_array($asset['activeLicence']) ? $asset['activeLicence'] : array();
        $licence_id = isset($licence['id']) ? sanitize_text_field($licence['id']) : '';
        $preview = isset($asset['previewUrl']) ? esc_url($asset['previewUrl']) : '';
        $title = isset($asset['title']) ? $asset['title'] : '';
        ?>
        <article style="border:1px solid #dcdcde;background:#fff;padding:12px">
            <?php if ($preview) : ?><img src="<?php echo $preview; ?>" alt="" loading="lazy" style="display:block;width:100%;height:170px;object-fit:cover;margin-bottom:10px" /><?php endif; ?>
            <h3 style="margin:0 0 6px"><?php echo esc_html($title); ?></h3>
            <p style="margin:0 0 8px;color:#50575e"><?php echo esc_html(implode(', ', array_filter(array(isset($asset['city']) ? $asset['city'] : '', isset($asset['province']) ? $asset['province'] : '')))); ?></p>
            <p style="margin:0 0 8px"><strong><?php echo esc_html__('Rights:', 'veld-archive'); ?></strong> <?php echo esc_html(isset($asset['rightsStatus']) ? $asset['rightsStatus'] : 'unknown'); ?><br /><strong><?php echo esc_html__('Licence:', 'veld-archive'); ?></strong> <?php echo esc_html($licence_id ? (isset($licence['type']) ? $licence['type'] : 'active') : __('Required in Stockvel', 'veld-archive')); ?></p>
            <?php if ($licence_id) : ?>
                <form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>" style="display:inline-block;margin-right:6px">
