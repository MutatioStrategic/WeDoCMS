final class Veld_Archive_WordPress_Connector {
    const VERSION = '0.1.0';
    const OPTION = 'veld_archive_connector';
    const CRON = 'veld_archive_connector_sync_notices';

    public static function boot() {
        $instance = new self();
        add_action('admin_menu', array($instance, 'admin_menu'));
        add_action('admin_post_veld_archive_pair', array($instance, 'pair'));
        add_action('admin_post_veld_archive_disconnect', array($instance, 'disconnect'));
        add_action('admin_post_veld_archive_import', array($instance, 'import_asset'));
        add_action('admin_post_veld_archive_hosted', array($instance, 'hosted_asset'));
        add_action(self::CRON, array($instance, 'sync_notices'));
        add_action('admin_notices', array($instance, 'admin_notices'));
        add_shortcode('veld_archive_image', array($instance, 'shortcode'));
    }

    public static function activate() {
        if (!wp_next_scheduled(self::CRON)) {
            wp_schedule_event(time() + HOUR_IN_SECONDS, 'twicedaily', self::CRON);
        }
    }

    public static function deactivate() {
        wp_clear_scheduled_hook(self::CRON);
    }

    public function admin_menu() {
        add_menu_page(
            __('Stockvel', 'veld-archive'),
            __('Stockvel', 'veld-archive'),
            'upload_files',
            'veld-archive',
            array($this, 'screen'),
            'dashicons-format-image',
            58
        );
    }

    public function screen() {
        if (!current_user_can('upload_files')) {
            wp_die(esc_html__('You do not have permission to use the Stockvel connector.', 'veld-archive'));
        }
        $settings = $this->settings();
        $query = isset($_GET['veld_q']) ? sanitize_text_field(wp_unslash($_GET['veld_q'])) : '';
        $results = array();
        $error = '';
        if ($query !== '' && $this->connected()) {
            $response = $this->api_request('GET', '/api/integrations/wordpress/v1/assets?' . http_build_query(array('q' => $query, 'kind' => 'image', 'limit' => 20)));
            if (is_wp_error($response)) {
                $error = $response->get_error_message();
            } else {
                $results = isset($response['results']) && is_array($response['results']) ? $response['results'] : array();
            }
        }
        ?>
        <div class="wrap">
            <h1><?php echo esc_html__('Stockvel', 'veld-archive'); ?></h1>
            <?php $this->render_messages(); ?>
            <?php if ($error) : ?><div class="notice notice-error"><p><?php echo esc_html($error); ?></p></div><?php endif; ?>
            <?php if (!$this->connected()) : ?>
                <div class="notice notice-info"><p><?php echo esc_html__('Connect this site with a ten-minute pairing code generated by an authorised Stockvel organisation user.', 'veld-archive'); ?></p></div>
            <?php endif; ?>
            <?php if (current_user_can('manage_options')) : ?>
                <h2><?php echo esc_html__('Connection', 'veld-archive'); ?></h2>
                <form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>">
                    <input type="hidden" name="action" value="veld_archive_pair" />
                    <?php wp_nonce_field('veld_archive_pair'); ?>
                    <table class="form-table" role="presentation">
                        <tr><th scope="row"><label for="veld-api-base-url"><?php echo esc_html__('Stockvel API base URL', 'veld-archive'); ?></label></th><td><input class="regular-text" id="veld-api-base-url" name="api_base_url" type="url" required value="<?php echo esc_attr($settings['api_base_url']); ?>" placeholder="https://veld-archive.pages.dev" /><p class="description"><?php echo esc_html__('Use the URL returned by the pairing screen, without credentials.', 'veld-archive'); ?></p></td></tr>
                        <tr><th scope="row"><label for="veld-pairing-code"><?php echo esc_html__('Pairing code', 'veld-archive'); ?></label></th><td><input class="regular-text" id="veld-pairing-code" name="pairing_code" type="password" autocomplete="off" required /><p class="description"><?php echo esc_html__('The code is used once and is not stored by WordPress after exchange.', 'veld-archive'); ?></p></td></tr>
                    </table>
                    <?php submit_button($this->connected() ? __('Replace connection', 'veld-archive') : __('Connect site', 'veld-archive')); ?>
                </form>
                <?php if ($this->connected()) : ?>
                    <p><strong><?php echo esc_html__('Connected site:', 'veld-archive'); ?></strong> <?php echo esc_html($settings['site_url']); ?> <span class="description">(<?php echo esc_html($settings['connection_id']); ?>)</span></p>
                    <form method="post" action="<?php echo esc_url(admin_url('admin-post.php')); ?>">
                        <input type="hidden" name="action" value="veld_archive_disconnect" />
                        <?php wp_nonce_field('veld_archive_disconnect'); ?>
                        <?php submit_button(__('Disconnect this site', 'veld-archive'), 'delete', 'submit', false); ?>
                    </form>
                <?php endif; ?>
            <?php endif; ?>
            <?php if ($this->connected()) : ?>
                <hr />
                <h2><?php echo esc_html__('Find approved imagery', 'veld-archive'); ?></h2>
                <form method="get">
                    <input type="hidden" name="page" value="veld-archive" />
                    <label for="veld-search-query" class="screen-reader-text"><?php echo esc_html__('Search Stockvel', 'veld-archive'); ?></label>
                    <input id="veld-search-query" name="veld_q" type="search" class="regular-text" value="<?php echo esc_attr($query); ?>" placeholder="Cape Town, mountain, market..." />
                    <?php submit_button(__('Search', 'veld-archive'), 'secondary', '', false); ?>
                </form>
                <?php if ($query !== '') : ?>
                    <div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(260px,1fr));gap:16px;margin-top:20px;max-width:1100px">
                    <?php foreach ($results as $asset) : $this->render_asset_card($asset); endforeach; ?>
